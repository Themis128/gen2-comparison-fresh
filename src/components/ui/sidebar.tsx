import * as React from 'react';

import { Slot } from '@radix-ui/react-slot';
import { cva, type VariantProps } from 'class-variance-authority';

import { cn } from '../../lib/utils';

const sidebarVariants = cva(
  'text-sidebar-foreground group flex flex-col overflow-hidden border-r bg-background',
  {
    variants: {
      variant: {
        default: 'border-sidebar-border',
        inset: 'border-sidebar-border bg-sidebar',
      },
      side: {
        left: '',
        right: 'border-l border-r-0',
      },
      collapsible: {
        offcanvas: '',
        icon: '',
        none: '',
      },
    },
    defaultVariants: {
      variant: 'default',
      side: 'left',
      collapsible: 'offcanvas',
    },
  }
);

const Sidebar = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & VariantProps<typeof sidebarVariants>
>(({ className, variant, side, collapsible = 'offcanvas', ...props }, ref) => {
  return (
    <div
      ref={ref}
      className={cn(sidebarVariants({ variant, side, collapsible }), className)}
      {...props}
    />
  );
});
Sidebar.displayName = 'Sidebar';

